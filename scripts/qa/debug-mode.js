async page => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const persisted = () => page.evaluate(() => localStorage.getItem('astronaut-academy-v1'));
  const debugMenu = async () => {
    await page.getByRole('button', { name: 'デバッグメニューを開く' }).click();
    await page.getByRole('dialog', { name: 'デバッグ · 全コンテンツ' }).waitFor();
  };
  const jump = async (name, phase) => {
    await debugMenu();
    await page.getByRole('button', { name: `${name}：${phase}`, exact: true }).click();
  };
  const courses = ['オリエンテーション', 'ISSシステム', '宇宙医学・生理学', '船外活動・中性浮力', 'ロボティクス', 'T-38飛行とサバイバル', '緊急事態対応', '地質学とアルテミス', '管制室総合演習'];
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:5181/');
  await page.getByRole('button', { name: /訓練を(開始|再開)する/ }).click();
  if (await page.getByRole('button', { name: 'SKIP ▸', exact: true }).isVisible()) await page.getByRole('button', { name: 'SKIP ▸', exact: true }).click();
  await page.getByText('訓練カリキュラム', { exact: true }).waitFor();
  const hubButtons = page.locator('ul').getByRole('button');
  check(await hubButtons.count() === 9, 'Expected nine normal courses');
  check(await hubButtons.evaluateAll(buttons => buttons.filter(b => !b.disabled).length) === 1, 'Normal mode must retain unlock gates');
  await page.getByRole('button', { name: '設定', exact: true }).click();
  await page.getByRole('button', { name: '低', exact: true }).click();
  if (await page.getByRole('button', { name: 'オン', exact: true }).isVisible()) await page.getByRole('button', { name: 'オン', exact: true }).click();
  await page.getByRole('button', { name: '閉じる', exact: true }).click();
  await hubButtons.filter({ has: page.getByText(courses[0], { exact: true }) }).click();
  await page.getByText('LESSON 01 / 10', { exact: true }).waitFor();
  await page.getByRole('button', { name: '次へ', exact: true }).click();
  await page.getByRole('button', { name: 'ハブ', exact: true }).click();
  const baseline = await persisted();
  check(JSON.parse(baseline).state.xp >= 20, 'Earned normal progress before debugging');
  await page.getByRole('button', { name: '設定', exact: true }).click();
  await page.getByRole('button', { name: 'デバッグで全て見る', exact: true }).click();
  await page.getByText('全9コース開放中 · 成績は保存されません', { exact: true }).waitFor();
  check(await hubButtons.evaluateAll(buttons => buttons.every(b => !b.disabled)), 'All nine debug courses must open');
  check(page.url().includes('debug=1'), 'Debug query must update');
  await debugMenu();
  check(await page.getByRole('dialog').getByRole('button', { name: /：/ }).count() === 36, 'Expected four entry points per course');
  await page.screenshot({ path: 'output/playwright/debug-menu-desktop.png' });
  await page.getByRole('button', { name: '閉じる', exact: true }).click();
  const visited = [];
  for (const name of courses) {
    await jump(name, 'レッスン');
    await page.getByText('LESSON 01 / 10', { exact: true }).waitFor();
    await page.getByRole('button', { name: '10', exact: true }).click();
    await page.getByText('LESSON 10 / 10', { exact: true }).waitFor();
    await jump(name, '知識確認');
    await page.getByRole('combobox', { name: 'デバッグ：表示する問題' }).selectOption('15');
    await page.getByText('Q16/16・正解 0', { exact: true }).waitFor();
    await page.getByRole('button', { name: '正解と解説を表示', exact: true }).click();
    await page.getByText('ANSWER · 正解', { exact: true }).waitFor();
    await page.getByRole('button', { name: '結果を見る', exact: true }).click();
    await page.getByText('デバッグ表示 · 成績は保存されません', { exact: true }).waitFor();
    await jump(name, '実技');
    await page.getByRole('button', { name: '訓練開始', exact: true }).waitFor();
    await page.waitForFunction(() => Number(document.querySelector('canvas')?.dataset.particleCount) > 0);
    const scene = await page.evaluate(() => ({ ...document.querySelector('canvas').dataset }));
    await page.getByRole('button', { name: '訓練開始', exact: true }).click();
    await page.getByRole('button', { name: '訓練開始', exact: true }).waitFor({ state: 'hidden' });
    await jump(name, '結果サンプル');
    await page.getByText('サンプル結果 · 成績・XP・バッジは保存されません', { exact: true }).waitFor();
    await page.getByRole('button', { name: '不合格結果サンプル', exact: true }).click();
    await page.getByText('400', { exact: true }).waitFor();
    check(await persisted() === baseline, `Progress changed in ${name}`);
    visited.push({ name, lessons: '1,10', question: 16, miniStarted: true, result: 400, scene });
  }
  await debugMenu();
  await page.getByRole('dialog').getByRole('button', { name: '復習', exact: true }).click();
  await page.getByText('DEBUG REVIEW · 各コースの問題サンプル', { exact: true }).waitFor();
  await page.getByRole('combobox', { name: 'デバッグ：表示する問題' }).selectOption('8');
  await page.getByRole('button', { name: '正解と解説を表示', exact: true }).click();
  await page.getByText('ANSWER · 正解', { exact: true }).waitFor();
  await page.getByRole('button', { name: '結果を見る', exact: true }).click();
  await page.getByText('REVIEW COMPLETE', { exact: true }).waitFor();
  await debugMenu();
  await page.getByRole('button', { name: 'バッジサンプル', exact: true }).click();
  await page.getByRole('dialog', { name: 'バッジコレクション' }).waitFor();
  check(await page.getByRole('dialog').locator('svg').count() === 9, 'Nine badge previews');
  await page.getByRole('button', { name: '閉じる', exact: true }).click();
  await debugMenu();
  await page.getByRole('button', { name: '修了証サンプル', exact: true }).click();
  await page.getByText('DEBUG PREVIEW · 修了証サンプル', { exact: false }).waitFor();
  await page.screenshot({ path: 'output/playwright/debug-certificate.png' });
  await page.getByRole('button', { name: 'ハブに戻る', exact: true }).click();
  check(await persisted() === baseline, 'Preview certificate changed saved record');
  await page.reload();
  await page.getByText('全9コース開放中 · 成績は保存されません', { exact: true }).waitFor();
  check(await persisted() === baseline, 'Reload changed saved record');
  await jump(courses[2], '実技');
  await page.getByRole('button', { name: '訓練開始', exact: true }).click();
  for (let month = 0; month < 6; month++) await page.getByRole('button', { name: 'この計画で30日を進める', exact: true }).click();
  await page.getByRole('button', { name: '評価を見る', exact: true }).click();
  await page.getByText('デバッグ結果 · 成績・XP・バッジは保存されません', { exact: true }).waitFor();
  check(await persisted() === baseline, 'Completing a real mini game changed saved record');
  await page.screenshot({ path: 'output/playwright/debug-mini-result.png' });
  await page.evaluate(report => { window.__debugQA = report; }, { visited, baseline: JSON.parse(baseline), errors, debugReload: true, progressPreserved: true });
}
